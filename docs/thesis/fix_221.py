def plain(p):
    return "".join(re.findall(r"<w:t[^>]*>(.*?)</w:t>", p, flags=re.S))


def runs(text):
    out = ""
    for part in re.split(r"(\[\[.*?\]\])", text):
        if not part:
            continue
        hl = part.startswith("[[")
        body = part[2:-2] if hl else part
        rpr = '<w:rPr><w:highlight w:val="yellow"/></w:rPr>' if hl else ""
        out += f'<w:r>{rpr}<w:t xml:space="preserve">{escape(body)}</w:t></w:r>'
    return out


def replace_par(startswith, *texts):
    global xml
    for m in re.finditer(r"<w:p[ >].*?</w:p>", xml, flags=re.S):
        if plain(m.group(0)).lstrip().startswith(startswith):
            ppr = re.search(r"<w:pPr>.*?</w:pPr>", m.group(0), flags=re.S)
            ppr = ppr.group(0) if ppr else ""
            new = "".join(f"<w:p>{ppr}{runs(t)}</w:p>" for t in texts)
            xml = xml[:m.start()] + new + xml[m.end():]
            return
    raise SystemExit("абзац не знайдено: " + startswith)


