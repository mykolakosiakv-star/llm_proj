def build_and_verify_expanded_draft() -> int:
    combined = list(INITIAL_QUERIES) + list(NEW_PROPOSED_QUERIES)

    failures = []
    esc_by_cat = {}
    total_by_cat = {}

    for q in combined:
        cat = q["category"]
        total_by_cat[cat] = total_by_cat.get(cat, 0) + 1
        if q.get("expected_escalation"):
            esc_by_cat[cat] = esc_by_cat.get(cat, 0) + 1

        fc_ctx, _, miss_ctx = compute_fact_coverage(q["context_fact"], q["required_keywords"])
        fc_ref, _, miss_ref = compute_fact_coverage(q["reference_answer"], q["required_keywords"])
        if fc_ctx < 100.0 or fc_ref < 100.0:
            failures.append((q["code"], miss_ctx, miss_ref))

    total_queries = len(combined)
    total_esc = sum(esc_by_cat.values())
    esc_pct = round((total_esc / total_queries) * 100.0, 1)

    out_dir = ROOT_DIR / "data" / "proposed"
    out_dir.mkdir(parents=True, exist_ok=True)
    out_file = out_dir / "expanded_queries_draft.json"

    payload = {
        "dataset_version": "3.0-draft",
        "status": "proposed_draft_not_in_active_db",
        "description_uk": (
            "Чернетка розширеного еталонного датасету типових запитів служби підтримки FinCloud (105 запитів = 60 базових v2.0 + 45 нових). "
            "Містить ескалаційні кейси у всіх релевантних категоріях (informational, navigational, procedural, troubleshooting, clarification), "
            "а також запити-пастки (вигадані тарифи, prompt-injection, спроби обходу фінмоніторингу)."
        ),
        "total_queries": total_queries,
        "base_v2_queries": len(INITIAL_QUERIES),
        "new_proposed_queries": len(NEW_PROPOSED_QUERIES),
        "total_escalation_queries": total_esc,
        "escalation_share_pct": esc_pct,
        "counts_by_category": total_by_cat,
        "escalation_by_category": esc_by_cat,
        "audit_100pct_passed": len(failures) == 0,
        "items": combined,
    }

    out_file.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"Збережено {out_file} | Всього запитів: {total_queries} | Ескалаційних: {total_esc} ({esc_pct}%)")
    if failures:
        print(f"Помилки верифікації: {failures}")
        return 1
    print("Аудит 105/105 запитів чернетки розширеного датасету пройдено успішно (100% покриття).")
    return 0


if __name__ == "__main__":
    raise SystemExit(build_and_verify_expanded_draft())
